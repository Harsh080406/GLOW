    page.drawText(`Destination: ${routeData.destination || "Main Campus"}`, { x: 300, y, size: 11, font });
    y -= 18;
    page.drawText(`Total Distance: ${routeData.distanceKm || 14.5} km`, { x: 30, y, size: 11, font });
    page.drawText(`Est. Travel Time: ${routeData.durationMin || 35} mins`, { x: 300, y, size: 11, font });

    // Table Header
    y -= 40;
    page.drawRectangle({ x: 30, y: y - 5, width: 540, height: 25, color: rgb(0.92, 0.94, 0.98) });
    page.drawText("#", { x: 40, y, size: 11, font: fontBold });
    page.drawText("Bus Stop Name", { x: 80, y, size: 11, font: fontBold });
    page.drawText("ETA Offset", { x: 320, y, size: 11, font: fontBold });
